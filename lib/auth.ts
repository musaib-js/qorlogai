import bcrypt from "bcryptjs";
import NextAuth from "next-auth";
import Credentials from "next-auth/providers/credentials";
import { z } from "zod";

import { consumeCode } from "@/lib/data/channels";
import { getUser, getUserByEmail } from "@/lib/data/users";

let dummy: string | null = null;
const dummyHash = () => (dummy ??= bcrypt.hashSync("qorlog-dummy-password", 12));

const credsSchema = z.object({ email: z.string().email(), password: z.string().min(1).max(200) });

export const { handlers, auth, signIn, signOut } = NextAuth({
  session: { strategy: "jwt", maxAge: 60 * 60 * 24 * 14 },
  pages: { signIn: "/login" },
  trustHost: true,
  providers: [
    Credentials({
      id: "credentials",
      credentials: { email: {}, password: {} },
      async authorize(raw) {
        const parsed = credsSchema.safeParse(raw);
        if (!parsed.success) return null;
        const user = await getUserByEmail(parsed.data.email);
        // Compare against a dummy hash when the user is unknown so timing doesn't reveal which emails exist.
        const ok = await bcrypt.compare(parsed.data.password, user?.passwordHash ?? dummyHash());
        if (!user || !ok || user.status !== "active") return null;
        return { id: user.id, name: user.name, email: user.email };
      },
    }),
    // One-time link generated by the Telegram bot (/web)
    Credentials({
      id: "link",
      credentials: { code: {} },
      async authorize(raw) {
        const code = typeof raw?.code === "string" ? raw.code : "";
        if (!code || code.length > 100) return null;
        const userId = await consumeCode(code, "web_login");
        if (!userId) return null;
        const user = await getUser(userId);
        if (!user || user.status !== "active") return null;
        return { id: user.id, name: user.name, email: user.email };
      },
    }),
  ],
  callbacks: {
    jwt({ token, user }) {
      if (user?.id) token.uid = user.id;
      return token;
    },
    session({ session, token }) {
      if (token.uid) session.user.id = token.uid as string;
      return session;
    },
  },
});

declare module "next-auth" {
  interface Session {
    user: { id: string } & import("next-auth").DefaultSession["user"];
  }
}
declare module "@auth/core/jwt" {
  interface JWT {
    uid?: string;
  }
}
